// Numbers are pixels too. The round medals differ even at the smallest size.
const DIGITS = {
  0: ['333', '323', '323', '323', '333'],
  1: ['.3.', '33.', '.3.', '.3.', '333'],
  2: ['333', '..3', '333', '3..', '333'],
  3: ['333', '..3', '333', '..3', '333'],
  4: ['3.3', '3.3', '333', '..3', '..3'],
};
function roundMedal(n) {
  const rows = sprite('..44....44/..444..444/...444444/..22222222/.2222222222/.2222222222/.2222222222/.2222222222/.2222222222/..22222222/...222222/....2222').map((s) => [...s]);
  [...String(n)].forEach((digit, i) => DIGITS[digit].forEach((row, y) => {
    [...row].forEach((pixel, x) => { if (pixel !== '.') rows[y + 4][x + 2 + i * 5] = pixel; });
  }));
  return Object.freeze(rows.map((row) => row.join('')));
}
for (const n of [10, 20, 30, 40]) ART[`round_${n}`] = roundMedal(n);
export const ACHIEVEMENT_ICONS = Object.freeze(ART);

const PALETTES = {
  gold: ['#44382b', '#a97b46', '#f4df9a', '#cf694b'],
  red: ['#482b30', '#a95046', '#f0c9a0', '#ef7355'],
  green: ['#273c38', '#68977c', '#d0e5b3', '#e1bf71'],
  blue: ['#293b50', '#5c8faa', '#c3e7ea', '#dbb76b'],
  locked: ['#30363d', '#555e67', '#84909a', '#707b84'],
};
const RED = new Set(['blood', 'headshot', 'monkey', 'swarm', 'jammer', 'knife', 'grenade', 'trap']);
const GREEN = new Set(['perks', 'medic', 'cache', 'supply', 'heli', 'luck']);
const BLUE = new Set(['frost', 'wonder', 'shield', 'skull', 'bone', 'dark', 'packed']);

/** Integer-aligned filled squares preserve both the caller's alpha and state. */
export function drawAchievementIcon(ctx, icon, x, y, scale = 2, unlocked = true) {
  const rows = ART[icon] ?? ART.medal;
  const palette = PALETTES[!unlocked ? 'locked' : RED.has(icon) ? 'red' : GREEN.has(icon) ? 'green' : BLUE.has(icon) ? 'blue' : 'gold'];
  const step = Math.max(1, Math.floor(Number.isFinite(scale) ? scale : 2));
  const ox = Math.round(x), oy = Math.round(y);
  ctx.save();
  for (let row = 0; row < rows.length; row++) {
    for (let col = 0; col < rows[row].length; col++) {
      const pixel = rows[row][col];
      if (pixel === '.') continue;
      ctx.fillStyle = palette[Number(pixel) - 1];
      ctx.fillRect(ox + col * step, oy + row * step, step, step);
    }
  }
  ctx.restore();
}
